function Y = SH_6_4_58
% ------------------------------------------------------------------------------
% 2024-08-22
%
% symmetric CHM(6) with d = 4 and L = 58
% ------------------------------------------------------------------------------

    w = exp(2j*pi/3);
    d = exp(1j*atan(2*sqrt(2)));
    f = -1 + sqrt(1/3 + w + 2j*sqrt(2)/3);
    e = -((2^(1/4)+1j*3^(1/4))*(3j+sqrt(3))) / (2^(3/4)*(62j*sqrt(2)-13+51j*sqrt(3)-6*sqrt(6))^(1/4));
    x = 2*e*(1j-sqrt(2))/(1j+2*sqrt(2)-sqrt(3)+sqrt(2*(1j-sqrt(2))*(sqrt(3)-3j))+2*(sqrt(2)-1j)*e*conj(f+1));
    g = -e*exp(1j*(2*pi/3 - atan(1/sqrt(2))/2));
    y = -g^2/x;
    c = g^2/e;

    Y = [
        1  1  1  1   1   1;
        1  w -1 -w   c  -c;
        1 -1  d -d   e  -e;
        1 -w -d  f^2 f   f;
        1  c  e  f   x   g;
        1 -c -e  f   g   y;
    ];

end
