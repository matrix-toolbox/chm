function Y = SH_6_4_34
% ------------------------------------------------------------------------------
% 2024-08-22
%
% symmetric CHM(6) with d = 4 and L = 34
% ------------------------------------------------------------------------------

    w = exp(2j*pi/3);
    d = (3+5j*sqrt(3)-4*exp(1j*pi/3)*sqrt(6)-(1+1j)*sqrt(3*(23j-8*sqrt(2)+9*sqrt(3))))/12;
    e = -d + sqrt(d)*sqrt(1-exp(2j*pi/3)+d+d*exp(2j*pi/3));
    c = d*w/e;

    Y = [
        1  1  1  1  1      1;
        1  w -1  c -w     -c;
        1 -1  d  e -e     -d;
        1  c  e -1 -e     -c;
        1 -w -e -e -e^2/d  c*e;
        1 -c -d -c  c*e   -c*d/e;
    ];

end
