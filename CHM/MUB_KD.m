function M = MUB_KD
% 2022-04-04
% 2022-12-11
%
% cf. MUB_KD.nb

    clc

    PL = PMv([4 5 2 3 6 1]);
    PR = PMv([5 4 2 1 6 3]);

    psi = acos(sqrt(sqrt(2)/3+1/2))/pi;
    %DL = diag(exp(1j*[4.7216869541120605 5.0615238635661814 0.7946961371248197 4.2761257001687225 5.50708511750949739 2.7053293733738387]));
    DL = diag(exp(2j*pi*[0, psi, 3/8, psi-1/8, 1/8, psi-3/8]));

    a = asin(-1/sqrt(3));
    b = 0;
    c = 7*pi/4;

    H1 = eye(6);
    H2 = D6(c)/sqrt(6);
    H3 = DL * PL * K6_2([a, b])/sqrt(6) * PR;

    disp('-------------------------------------------------------------------------------');

    M1 = H1'*H2;
    abs(sqrt(6)*M1).^2
    M1*M1'

    M2 = H1'*H3;
    abs(sqrt(6)*M2).^2
    M2*M2'

    M3 = H2'*H3;
    abs(sqrt(6)*M3).^2
    M3*M3'

    disp('-------------------------------------------------------------------------------');



end
