function H = F4(p)
% ------------------------------------------------------------------------------
% 2016-12-05 Wojciech Bruzda, name[at]uj.edu.pl : name = w.bruzda, https://matrix-toolbox.github.io/chm
% ------------------------------------------------------------------------------
% Fourier CHM depending on 1 parameter;
%
% >> H = F4(rand);
% ------------------------------------------------------------------------------

    R = [
        0 0 0 0;
        0 p(1) 0 p(1);
        0 0 0 0;
        0 p(1) 0 p(1);
    ];

    H = FN(4) .* exp(2j * pi * R);
end
